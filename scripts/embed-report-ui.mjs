import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Embeds the built report app into a generated TypeScript module the CLI bundles, keeping report
// files self-contained with zero runtime file reads.
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const js = readFileSync(join(root, "report-ui/dist/report-app.js"), "utf8");
const css = readFileSync(join(root, "report-ui/dist/report-app.css"), "utf8");
const banner = "// Auto-generated by scripts/embed-report-ui.mjs - do not edit.\n";
mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(
  join(root, "src/generated/report-assets.ts"),
  `${banner}export const REPORT_APP_JS: string = ${JSON.stringify(js)};\nexport const REPORT_APP_CSS: string = ${JSON.stringify(css)};\n`,
);
console.log(
  `embedded report app: ${(js.length / 1024).toFixed(0)}KB js, ${(css.length / 1024).toFixed(0)}KB css`,
);
